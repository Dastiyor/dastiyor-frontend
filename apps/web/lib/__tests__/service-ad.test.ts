import { looksLikeServiceAd } from '../service-ad';

describe('looksLikeServiceAd', () => {
    it.each([
        ['Предлагаю свои услуги электрика', 'Любые работы по электрике'],
        ['Ремонт квартир', 'Выполняю ремонт квартир качественно и недорого'],
        ['Сантехник', 'Опыт работы 10 лет. Звоните в любое время'],
        ['Грузоперевозки', 'Принимаю заказы по всему Душанбе, пишите в WhatsApp'],
        ['Мы выполняем отделочные работы', 'Бригада, гарантия'],
        ['Ищу работу', 'Могу работать грузчиком'],
        ['Хизматрасонии барқкашӣ', 'Хизматҳои худро пешниҳод мекунам, занг занед'],
        ['Таъмири хона', 'Сифатнок ва арзон иҷро мекунам'],
        ['Устои сантехник', 'Фармоиш қабул мекунам'],
    ])('flags an ad: %s', (title, description) => {
        expect(looksLikeServiceAd(title, description)).toBe(true);
    });

    it.each([
        ['Нужен сантехник', 'Течёт кран на кухне, нужно заменить смеситель'],
        ['Уборка квартиры', 'Требуется генеральная уборка, 3 комнаты. Недорого, звоните'],
        ['Ищу мастера по ремонту стиральной машины', 'Не отжимает, гарантия закончилась'],
        ['Перевезти диван', 'С Сино на Шохмансур, в субботу'],
        ['Репетитор по английскому', 'Для ребёнка 10 лет, два раза в неделю'],
        ['Ба ман усто лозим аст', 'Таъмири ошхона, арзон'],
        ['Тоза кардани хона', 'Се ҳуҷра, рӯзи шанбе'],
    ])('leaves a real task alone: %s', (title, description) => {
        expect(looksLikeServiceAd(title, description)).toBe(false);
    });

    it('treats ё and е alike', () => {
        expect(looksLikeServiceAd('Берём заказы', '')).toBe(true);
        expect(looksLikeServiceAd('Берем заказы', '')).toBe(true);
    });
});
